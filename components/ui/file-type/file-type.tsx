export function getFileTypeCategory(type?: string): FileTypeCategory {
  const key = (type ?? "").trim().toLowerCase().replace(/^\.+/, "")
  if (!key) return "empty"
  if (key === "file") return "file"
  if (FILE_TYPE_CATEGORIES.includes(key as FileTypeCategory)) return key as FileTypeCategory
  return family[key] ?? "file"
}

export function getFileType(input?: string | File | { name?: string; type?: string }): string {
  if (typeof input !== "string") {
    if (!input) return "empty"
    const mime = input.type?.toLowerCase()
    if (mime && mimeTypes[mime]) return mimeTypes[mime]
    if (mime?.startsWith("image/")) return "image"
    if (mime?.startsWith("video/")) return "video"
    if (mime?.startsWith("audio/")) return "audio"
    if (mime?.startsWith("font/")) return "font"
    return getFileType(input.name ?? "")
  }
  let value = input.trim().toLowerCase()
  if (/^[a-z][\w+.-]*:\/\/[^/]*/.test(value)) value = value.split(/[?#]/)[0].replace(/^[a-z][\w+.-]*:\/\/[^/]*/, "")
  else if (!/(\.\d*[a-z][a-z\d]*|[\\/])$/.test(value)) value = value.split(/[?#]/)[0]
  if (!value) return "empty"
  if (value.endsWith("/") || value.endsWith("\\")) return "folder"
  const mime = value.split(";")[0].trim()
  if (/^(application|audio|font|image|message|model|multipart|text|video)\/[\w.+-]+$/.test(mime)) {
    if (mimeTypes[mime]) return mimeTypes[mime]
    const [mediaFamily, subtype] = mime.split("/")
    if (family[subtype] && (mediaFamily === "application" || mediaFamily === "text" || family[subtype] === mediaFamily)) return subtype
    if (["image", "video", "audio", "font"].includes(mediaFamily)) return mediaFamily
    return "empty"
  }
  const name = value.split(/[\\/]/).at(-1) ?? ""
  const exactNames: Record<string, string> = { containerfile: "dockerfile", gnumakefile: "makefile", ".dev.vars": "env", ".gitignore": "git", ".gitattributes": "git", ".gitmodules": "git", ".gitkeep": "git", ".gitconfig": "git", ".mailmap": "git", "bun.lockb": "lock", "go.sum": "lock", "go.mod": "go", "go.work": "go", gemfile: "rb", rakefile: "rb", brewfile: "rb", podfile: "rb", vagrantfile: "rb", fastfile: "rb", ".bashrc": "bash", ".bash_profile": "bash", ".bash_aliases": "bash", ".bash_logout": "bash", ".zshrc": "zsh", ".zprofile": "zsh", ".zshenv": "zsh", ".zlogin": "zsh", ".envrc": "sh", ".profile": "sh", ".editorconfig": "ini", ".npmrc": "ini", ".pypirc": "ini", ".flake8": "ini", ".pylintrc": "ini", ".coveragerc": "ini", caddyfile: "conf", ".htaccess": "conf", ".babelrc": "json", ".swcrc": "json", ".cursorrules": "md", readme: "txt", license: "txt", licence: "txt", changelog: "txt", codeowners: "txt", ".nvmrc": "txt", ".node-version": "txt", ".python-version": "txt", ".ruby-version": "txt", ".tool-versions": "txt", ".terraform-version": "txt" }
  if (exactNames[name]) return exactNames[name]
  if (name.startsWith(".env.")) return "env"
  if (/^(docker|container)file\./.test(name)) return "dockerfile"
  if (/^\.[\w-]+ignore$/.test(name)) return "ignore"
  const extension = name.slice(name.lastIndexOf(".") + 1)
  const aliases: Record<string, string> = { cer: "crt", mak: "makefile", mk: "makefile", sqlite3: "sqlite" }
  if (aliases[extension]) return aliases[extension]
  return name.lastIndexOf(".") <= 0 && !family[extension] ? "empty" : extension || "empty"
}

function FileType({ type, variant = "outline", size = "default", label, glyph = false, icon, labelClassName, className, ...props }: Omit<React.ComponentProps<"span">, "children"> & { type?: string; variant?: FileTypeVariant; size?: "mini" | "xs" | "sm" | "default" | "lg" | "xl"; label?: React.ReactNode; glyph?: boolean; icon?: React.ReactNode; labelClassName?: string }) {
  const value = (type ?? "").trim().replace(/^\.+/, "").toLowerCase()
  const resolvedType = value || "empty"
  const category = getFileTypeCategory(value)
  const tone = tones[category]
  const displayLabel = label === undefined ? (family[value] || category === "file" ? extensionStyles[value]?.label ?? value.toUpperCase() : "") : label
  const showLabel = displayLabel !== "" && displayLabel !== null && displayLabel !== undefined && !glyph && icon === undefined
  const showGlyph = !showLabel && icon === undefined
  const Glyph = glyphs[category]
  const dimension = { mini: "size-[18px]", xs: "size-6", sm: "size-8", default: "size-10", lg: "size-12", xl: "size-14" }[size]
  const categoryClass = variant === "mono" ? "text-muted-foreground" : extensionStyles[value]?.color ?? tone.color
  const surface = variant === "light" ? `bg-current/10` : ""
  const name = displayLabel ? `${typeof displayLabel === "string" ? displayLabel : resolvedType.toUpperCase()} file` : familyName[category]
  return (
    <span role="img" aria-label={name} data-slot="file-type" data-type={resolvedType} data-category={category} data-variant={variant} data-size={size} className={cn("@container relative inline-grid shrink-0 place-items-center overflow-hidden rounded-md border p-1.5", dimension, variants[variant], variant !== "mono" && categoryClass, surface, className)} {...props}>
      <svg viewBox="0 0 24 24" fill="none" aria-hidden="true" className="absolute inset-0 size-full">
        <path d="M6 22a2 2 0 0 1-2-2V4a2 2 0 0 1 2-2h7.586a2 2 0 0 1 1.414.586l4.414 4.414A2 2 0 0 1 20 8.414V20a2 2 0 0 1-2 2Z" stroke="currentColor" strokeWidth="1.2" fill={variant === "solid" ? "currentColor" : "transparent"} />
        {variant === "solid" && <path d="M13.586 2a2 2 0 0 1 1.414.586l4.414 4.414A2 2 0 0 1 20 8.414V8h-5a1 1 0 0 1-1-1V2Z" fill="white" opacity=".3" />}
        <path d="M14 2v5a1 1 0 0 0 1 1h5" stroke="currentColor" strokeWidth="1.2" />
        {showGlyph && !icon && <g transform="translate(6 11) scale(.75)"><Glyph aria-hidden="true" className={cn("size-4", variant === "solid" && "text-white")} /></g>}
        {showLabel && !labelClassName && <g><rect x="4.5" y="13.5" width="15" height="5" rx="1" fill={variant === "solid" ? "transparent" : "currentColor"} /><text x="12" y="17.3" textAnchor="middle" fontSize="3.6" fontWeight="700" fill="white">{String(displayLabel).toUpperCase().slice(0, 5)}</text></g>}
      </svg>
      {showLabel && labelClassName && <span data-slot="file-type-label" className={cn("absolute left-[5%] top-[45%] z-10 flex h-[35%] max-w-[95%] items-center justify-center truncate rounded-[10cqw] bg-current px-[7cqw] text-[6px] font-medium leading-none text-white", variant === "solid" && "bg-transparent", labelClassName)}>{displayLabel}</span>}
      {icon && <span aria-hidden="true" className={cn("absolute left-1/2 top-[62.5%] z-10 flex size-[38%] -translate-x-1/2 -translate-y-1/2 items-center justify-center", variant === "solid" && "text-white", "[&>svg]:size-full")}>{icon}</span>}
    </span>
  )
}

export { FileType }
